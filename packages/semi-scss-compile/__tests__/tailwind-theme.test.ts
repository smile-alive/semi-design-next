import fs from 'node:fs';
import path from 'node:path';
import { expect, it } from 'vite-plus/test';
import { compileTailwindTheme } from '../src/index';

const foundationPath = path.resolve(import.meta.dirname, '../../semi-foundation/src');
const themePath = path.join(foundationPath, 'theme');
const css = compileTailwindTheme({ foundationPath });
const mapped = new Map([...css.matchAll(/^\s*(--[\w-]+): var\((--semi-[\w-]+)\);$/gm)].map(([, key, name]) => [name, key]));

it('生成的文件是 @theme inline 且带有生成说明', () => {
    expect(css).toMatch(/^\/\* Generated by .* do not edit \*\/\n@theme inline \{\n/);
    expect(css).not.toContain('@custom-variant');
    // every entry is a plain `var(--semi-*)` reference
    expect(css.split('\n').filter((line) => line.startsWith('    --'))).toHaveLength(mapped.size);
});

it('所有非渐变的 --semi-color-* 都被映射', () => {
    const source = fs.readFileSync(path.join(themePath, 'global.scss'), 'utf-8');
    const expected = new Set([...source.matchAll(/^\s*(--semi-color-[\w-]+):\s*(.+?);/gm)].filter(([, , value]) => !value.startsWith('linear-gradient') && !value.includes('--semi-ai-general-')).map(([, name]) => name));
    expect(expected.size).toBeGreaterThan(100);
    expect([...expected].filter((name) => mapped.get(name) !== name.replace('--semi-color-', '--color-semi-color-'))).toEqual([]);
    expect(mapped.get('--semi-color-ai-purple')).toBe('--color-semi-color-ai-purple');
    expect(mapped.has('--semi-color-ai-general')).toBe(false);
});

it('阴影、6 个圆角、5 个缓动都在', () => {
    expect(mapped.get('--semi-shadow-elevated')).toBe('--shadow-semi-elevated');
    expect([...mapped.keys()].filter((name) => name.startsWith('--semi-border-radius-'))).toHaveLength(6);
    expect([...mapped.values()].filter((key) => key.startsWith('--ease-semi-'))).toHaveLength(5);
});

it('间距、字号与行高、字重、字体族 token 全部映射到对应命名空间', () => {
    const source = fs.readFileSync(path.join(themePath, 'global.scss'), 'utf-8');
    const namespaces: [RegExp, (rest: string) => string][] = [
        [/^--semi-spacing-(.+)$/, (rest) => `--spacing-semi-${rest}`],
        [/^--semi-font-size-(.+)$/, (rest) => `--text-semi-${rest}`],
        [/^--semi-line-height-(.+)$/, (rest) => `--text-semi-${rest}--line-height`],
        [/^--semi-font-weight-(.+)$/, (rest) => `--font-weight-semi-${rest}`],
        [/^--semi-font-family-(.+)$/, (rest) => `--font-semi-family-${rest}`],
    ];
    const declared = [...new Set([...source.matchAll(/^\s*(--semi-[\w-]+):/gm)].map(([, name]) => name))];
    const wrong = namespaces.flatMap(([pattern, key]) => {
        const names = declared.filter((name) => pattern.test(name));
        expect(names.length).toBeGreaterThan(0);
        return names.filter((name) => mapped.get(name) !== key(name.replace(pattern, '$1')));
    });
    expect(wrong).toEqual([]);
    expect(mapped.get('--semi-font-family-regular')).toBe('--font-semi-family-regular');
    expect(mapped.get('--semi-line-height-regular')).toBe('--text-semi-regular--line-height');
});

it('每个调色板颜色都映射为 --color-semi-<色名>，渐变除外', () => {
    const source = fs.readFileSync(path.join(themePath, '_palette.scss'), 'utf-8');
    const palette = new Set([...source.matchAll(/^\s*(--semi-[\w-]+):\s*(.+?);?$/gm)].filter(([, , value]) => !value.startsWith('linear-gradient')).map(([, name]) => name));
    expect(palette.size).toBe(212);
    expect([...palette].filter((name) => mapped.get(name) !== name.replace('--semi-', '--color-semi-'))).toEqual([]);
    expect(mapped.get('--semi-white')).toBe('--color-semi-white');
    expect(mapped.get('--semi-ai-general-5-0')).toBe('--color-semi-ai-general-5-0');
    expect(mapped.has('--semi-ai-general-5')).toBe(false);
});

it('其余 token 不进入映射', () => {
    expect(css).not.toContain('--semi-transition_duration');
    expect(css).not.toContain('--semi-button-colorful');
    expect(css).not.toMatch(/--semi-(z-|height-control-|border-thickness)/);
    for (const key of mapped.values()) {
        expect(key).toMatch(/^--(color-semi|radius-semi|shadow-semi|ease-semi|spacing-semi|text-semi|font-weight-semi|font-semi-family)-/);
    }
});
